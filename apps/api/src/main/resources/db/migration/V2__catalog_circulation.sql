create table category (
    id bigint generated by default as identity primary key,
    name varchar(120) not null unique
);

create table title (
    id bigint generated by default as identity primary key,
    name varchar(255) not null,
    author varchar(255) not null,
    isbn varchar(32),
    category_id bigint references category (id),
    price_vnd integer not null,
    loanable boolean not null,
    active boolean not null
);

create table book_copy (
    id bigint generated by default as identity primary key,
    title_id bigint not null references title (id),
    code varchar(64) not null unique,
    status varchar(32) not null,
    shelf varchar(80),
    loanable_override boolean,
    version bigint not null
);

create table lending_policy (
    id smallint primary key,
    max_active_loans integer not null,
    loan_days integer not null,
    max_renewals integer not null,
    renew_days integer not null,
    fine_per_day_vnd integer not null,
    fine_block_vnd integer not null,
    hold_hours integer not null,
    max_open_reservations integer not null,
    lost_processing_fee_vnd integer not null
);

insert into lending_policy (
    id, max_active_loans, loan_days, max_renewals, renew_days,
    fine_per_day_vnd, fine_block_vnd, hold_hours, max_open_reservations, lost_processing_fee_vnd
) values (1, 5, 14, 1, 7, 2000, 50000, 48, 3, 0);

create table loan (
    id bigint generated by default as identity primary key,
    copy_id bigint not null references book_copy (id),
    title_id bigint not null references title (id),
    reader_id bigint not null references app_user (id),
    status varchar(20) not null,
    borrowed_at timestamp not null,
    due_at timestamp not null,
    returned_at timestamp,
    renew_count integer not null
);

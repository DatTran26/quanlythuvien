create table fine (
    id bigint generated by default as identity primary key,
    loan_id bigint references loan (id),
    reader_id bigint not null references app_user (id),
    amount_vnd integer not null,
    balance_vnd integer not null,
    reason varchar(20) not null,
    status varchar(20) not null,
    note varchar(500),
    created_at timestamp not null
);

create table reservation (
    id bigint generated by default as identity primary key,
    title_id bigint not null references title (id),
    reader_id bigint not null references app_user (id),
    status varchar(20) not null,
    held_copy_id bigint references book_copy (id),
    created_at timestamp not null,
    ready_until timestamp
);

create table damage_report (
    id bigint generated by default as identity primary key,
    copy_id bigint not null references book_copy (id),
    reporter_id bigint not null references app_user (id),
    status varchar(20) not null,
    severity varchar(20) not null,
    note varchar(500),
    photo_path varchar(255),
    created_at timestamp not null
);

create table app_notification (
    id bigint generated by default as identity primary key,
    user_id bigint not null references app_user (id),
    title varchar(160) not null,
    body varchar(500) not null,
    read_at timestamp,
    created_at timestamp not null
);

create table audit_log (
    id bigint generated by default as identity primary key,
    actor_id bigint references app_user (id),
    action varchar(80) not null,
    entity_type varchar(40) not null,
    entity_id varchar(40) not null,
    detail varchar(500),
    created_at timestamp not null
);
